/// The standard-library package a Python module belongs to: its top-level
/// module (`os` for `os.path`), when that is part of the standard library.
/// Relative modules (`.util`) never are.
pub(crate) fn python_stdlib_package(module: &str) -> Option<&'static str> {
    let top = module.split('.').next()?;
    PYTHON_STDLIB_MODULES
        .iter()
        .find(|name| **name == top)
        .copied()
}

pub(crate) fn is_python_builtin(name: &str) -> bool {
    PYTHON_BUILTINS.contains(&name)
}

/// Functions of the standard library that return one of its own objects
/// (`logging.getLogger` a `Logger`, `re.compile` a `Pattern`).
const PYTHON_STDLIB_FACTORIES: &[&str] = &[
    "logging.getLogger",
    "re.compile",
    "re.fullmatch",
    "re.match",
    "re.search",
    "sqlite3.connect",
    "subprocess.run",
    "threading.current_thread",
];

/// Whether calling the standard-library `symbol` constructs a value of the
/// standard library: a class (`pathlib.Path`, `collections.Counter`), a
/// builtin type, or a factory of one (`logging.getLogger`), not a function
/// that may return anything (`importlib.import_module`).
pub(crate) fn python_constructs_stdlib_value(package: &str, symbol: &str) -> bool {
    if package == "builtins" {
        return PYTHON_BUILTIN_CONSTRUCTORS.contains(&symbol);
    }
    if PYTHON_STDLIB_FACTORIES.contains(&symbol) {
        return true;
    }
    symbol
        .rsplit('.')
        .next()
        .is_some_and(|name| name.starts_with(|c: char| c.is_ascii_uppercase()))
}
