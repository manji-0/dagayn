/// Directories of POSIX headers (`<sys/socket.h>`, `<netinet/in.h>`).
const POSIX_HEADER_DIRS: &[&str] = &["sys/", "netinet/", "arpa/", "net/"];

/// The standard-library package an angle-bracket include names (`libc` for
/// `<stdio.h>`, `posix` for `<unistd.h>` or `<sys/socket.h>`). A quoted
/// include is the repository's and never reaches this.
pub(crate) fn c_header_package(header: &str) -> Option<&'static str> {
    if LIBC_HEADERS.contains(&header) {
        Some("libc")
    } else if is_posix_header(header) {
        Some("posix")
    } else {
        None
    }
}

fn is_posix_header(header: &str) -> bool {
    POSIX_HEADERS.contains(&header)
        || POSIX_HEADER_DIRS.iter().any(|dir| {
            header
                .strip_prefix(dir)
                .is_some_and(|rest| rest.ends_with(".h"))
        })
}

