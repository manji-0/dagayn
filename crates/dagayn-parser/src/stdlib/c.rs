/// The header declaring a libc / POSIX function `name` and the package it
/// belongs to (`("stdlib.h", "libc")` for `malloc`).
pub(crate) fn c_function_header(name: &str) -> Option<(&'static str, &'static str)> {
    C_FUNCTIONS
        .iter()
        .find(|(function, _)| *function == name)
        .and_then(|(_, header)| Some((*header, c_header_package(header)?)))
}

/// Whether including `included` declares what `header` declares: the header
/// itself, or its C++ spelling (`<cstdio>` for `stdio.h`).
pub(crate) fn c_header_satisfied_by(header: &str, included: &str) -> bool {
    included == header
        || header
            .strip_suffix(".h")
            .is_some_and(|stem| !stem.contains('/') && included.strip_prefix('c') == Some(stem))
}
