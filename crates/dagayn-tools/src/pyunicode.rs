//! Python's Unicode classes for `str`: `re`'s `\w` and `\d`, and
//! `str.isprintable()` (which decides what `repr` escapes).
//!
//! The tables are Python's own answer for every code point (CPython 3.14,
//! Unicode 16.0.0); `tests/test_pyunicode_tables.py` recomputes them from the
//! running interpreter and fails, printing the new tables, when they drift.

fn in_table(table: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    table
        .binary_search_by(|&(start, end)| {
            if end < cp {
                std::cmp::Ordering::Less
            } else if start > cp {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// `re.match(r"\w", c)`: `c.isalnum()` or `_`.
pub(crate) fn is_word(c: char) -> bool {
    in_table(WORD, c)
}

/// `re.match(r"\d", c)`: a decimal digit (`Nd`).
pub(crate) fn is_digit(c: char) -> bool {
    in_table(DIGIT, c)
}

/// `c.isprintable()`.
pub(crate) fn is_printable(c: char) -> bool {
    !in_table(NOT_PRINTABLE, c)
}

/// `repr(text)` of a `str`.
pub(crate) fn repr(text: &str) -> String {
    let quote = if text.contains('\'') && !text.contains('"') {
        '"'
    } else {
        '\''
    };
    let mut out = String::from(quote);
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c == quote => {
                out.push('\\');
                out.push(c);
            }
            c if is_printable(c) => out.push(c),
            c if (c as u32) < 0x100 => out.push_str(&format!("\\x{:02x}", c as u32)),
            c if (c as u32) < 0x10000 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push_str(&format!("\\U{:08x}", c as u32)),
        }
    }
    out.push(quote);
    out
}

/// Whether `\b` holds at `index` of `chars`: a `\w` on exactly one side.
pub(crate) fn is_word_boundary(chars: &[char], index: usize) -> bool {
    let before = index > 0 && is_word(chars[index - 1]);
    let after = index < chars.len() && is_word(chars[index]);
    before != after
}

/// `re.search(rf"\b{re.escape(word)}\b", text)`.
pub(crate) fn contains_bounded(text: &str, word: &str) -> bool {
    let text: Vec<char> = text.chars().collect();
    let word: Vec<char> = word.chars().collect();
    if word.len() > text.len() {
        return false;
    }
    (0..=text.len() - word.len()).any(|start| {
        text[start..start + word.len()] == word[..]
            && is_word_boundary(&text, start)
            && is_word_boundary(&text, start + word.len())
    })
}

