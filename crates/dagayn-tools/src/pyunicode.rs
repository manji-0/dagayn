#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn classes_follow_python() {
        // `\w` is `isalnum()`: letters and every numeric, not marks or `Pc`
        // other than `_`.
        for c in [
            'a', 'é', '中', '_', '5', '\u{0663}', '\u{2160}', '\u{00b2}', '\u{2460}',
        ] {
            assert!(is_word(c), "{c:?}");
        }
        for c in ['\u{0301}', '\u{093e}', '\u{203f}', '-', ' ', '\u{200b}'] {
            assert!(!is_word(c), "{c:?}");
        }
        assert!(is_digit('\u{0663}') && !is_digit('\u{00b2}') && !is_digit('\u{2160}'));
        assert_eq!(repr("a'b"), "\"a'b\"");
        assert_eq!(
            repr("\u{a0}\u{200b}\u{e0001}é\x7f"),
            "'\\xa0\\u200b\\U000e0001é\\x7f'"
        );
    }

    #[test]
    fn bounded_matches_need_a_word_edge_on_each_side() {
        assert!(contains_bounded("from a import helper", "helper"));
        assert!(!contains_bounded("from a import helpers", "helper"));
        assert!(!contains_bounded("import éhelper", "helper"));
        assert!(contains_bounded("import \u{0301}helper", "helper"));
        // A non-word edge in the name needs a word character beside it.
        assert!(contains_bounded("x.y", ".y"));
        assert!(!contains_bounded(" .y", ".y"));
    }
}
